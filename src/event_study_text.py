"""M3: text-derived signals in the event study. PRELIMINARY.
(1) Validation: do classifier-based MFA threat/action intensities and MND PLA activity spike at curated events?
(2) Cost: treat high-intensity signal days (z>3 vs trailing 60 obs, merged within 10 d) as events; event study of
    weather-adjusted abnormal transits (same model as src/event_study.py). (3) Weekly lagged regressions."""
import warnings; warnings.filterwarnings("ignore")
import pathlib, numpy as np, pandas as pd, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
import statsmodels.api as sm
ROOT = pathlib.Path(__file__).resolve().parents[1]
P = pd.read_csv(ROOT / "data/processed/daily_panel.csv", index_col=0, parse_dates=True)
S = pd.read_csv(ROOT / "data/processed/text_signals_daily.csv", index_col=0, parse_dates=True)
EV = pd.read_csv(ROOT / "data/raw/coercion_events_curated.csv", parse_dates=["event_date", "end_date", "public_date"])
rng = np.random.default_rng(1); PRE, WIN, POST, NPL = (-28, -8), (-14, 21), (0, 14), 2000
near_any = pd.Series(False, index=P.index)
for d in EV.public_date: near_any |= (P.index >= d - pd.Timedelta(days=14)) & (P.index <= d + pd.Timedelta(days=14))
def resid(strait):
    y = np.log1p(P[f"transits_{strait}"])
    X = pd.get_dummies(pd.DataFrame({"dow": P.index.dayofweek, "m": P.index.month, "y": P.index.year}, index=P.index).astype(str), drop_first=True).astype(float)
    for L in range(3): X[f"w{L}"] = P[f"wave_{strait}"].shift(L)
    for L in range(4): X[f"tc{L}"] = P[f"tc300_{strait}"].shift(L)
    X["tcw"] = P[f"tcwind500_{strait}"]; X = sm.add_constant(X); ok = X.notna().all(axis=1) & y.notna()
    m = sm.OLS(y[ok & ~near_any], X[ok & ~near_any]).fit(); return (y - m.predict(X)).where(ok).rolling(7, center=True, min_periods=5).mean()
def path(s, d0):
    if d0 not in s.index: return None
    i = s.index.get_loc(d0)
    if i + WIN[0] + PRE[0] < 0 or i + WIN[1] >= len(s): return None
    base = s.iloc[i + PRE[0]: i + PRE[1] + 1].mean(); return None if np.isnan(base) else s.iloc[i + WIN[0]: i + WIN[1] + 1].values - base
def study(s, dates, pool_mask):
    paths = np.array([p for d in dates if (p := path(s, d)) is not None]); k = len(paths)
    pool = s.index[pool_mask.reindex(s.index).fillna(False).values][40:-30]
    plac = np.array([np.nanmean([p for d in rng.choice(pool, k, replace=False) if (p := path(s, d)) is not None], axis=0) for _ in range(NPL)])
    days = np.arange(WIN[0], WIN[1] + 1); post = (days >= POST[0]) & (days <= POST[1]); m = np.nanmean(paths, 0)
    car = np.nanmean(m[post]); return dict(days=days, m=m, plac=plac, k=k, car=car, p=(np.abs(np.nanmean(plac[:, post], 1)) >= abs(car)).mean(),
                                          pre=np.nanmean(m[(days >= -7) & (days <= -1)]))
def zser(x, w=60):
    x = x.dropna(); return (x - x.rolling(w, min_periods=20).median().shift(1)) / x.rolling(w, min_periods=20).std().shift(1)
def spikes(x, thr=3, gap=10):
    z = zser(x); out = []
    for d in z[z > thr].index:
        if not out or (d - out[-1]).days > gap: out.append(d)
    return out
f = lambda x: f"{100*(np.exp(x)-1):+.1f}%"
L = ["# M3 results: text-derived signals (auto-generated by src/event_study_text.py) — PRELIMINARY\n"]
L.append("MFA series come from the T+B1 classifier (macro-F1 0.859, κ 0.758 on 189 held-out sentences vs. a second, independent "
         "AI annotator; see reports/classifier_metrics.md). Labels come from two AI annotators (inter-annotator κ 0.935); "
         "**no human-annotated validation yet** (a human spot-check of 40 sentences is planned). "
         "MFA website boilerplate (exit-site popup, copyright footer; 288 rows) is excluded from the corpus.\n")
cov = {c: (S[c].dropna().index.min().date(), S[c].dropna().index.max().date(), S[c].notna().sum()) for c in ["mfa_threat_share", "mnd_aircraft", "mnd_ships"]}
L.append("Coverage: " + "; ".join(f"{k}: {a}→{b} ({n} days)" for k, (a, b, n) in cov.items()))
L.append("\n## (1) Validation: max z-score of signal within 0..+3 days of curated events (z vs trailing 60 observations)\n")
L.append("| signal | event group | N in coverage | median z | share z>2 |"); L.append("|---|---|---|---|---|")
for col in ["mfa_threat_share", "mfa_threat_novel_share", "mfa_action_share", "mnd_aircraft", "mnd_ships"]:
    z = zser(S[col])
    for grp, sel in [("threats", EV.category == "threat"), ("TW actions", (EV.category == "action") & (EV.theater == "taiwan")), ("SCS actions", (EV.category == "action") & (EV.theater != "taiwan"))]:
        vals = [z.loc[d: d + pd.Timedelta(days=3)].max() for d in EV[sel].public_date if z.index.min() + pd.Timedelta(days=60) <= d <= z.index.max()]
        vals = pd.Series(vals).dropna()
        if len(vals): L.append(f"| {col} | {grp} | {len(vals)} | {vals.median():.1f} | {(vals > 2).mean():.0%} |")
L.append("\n## (2) Cost side: signal-spike days as events (weather-adjusted abnormal transits, days 0..14)\n")
L.append("| signal spikes (z>3) | chokepoint | N | effect | placebo p | pre-trend |"); L.append("|---|---|---|---|---|---|")
R = {}
for sig in ["mfa_threat_share", "mfa_threat_novel_share", "mfa_action_share", "mnd_aircraft"]:
    ds = spikes(S[sig]); mask = pd.Series(True, index=P.index)
    for d in ds: mask &= ~((P.index >= d - pd.Timedelta(days=14)) & (P.index <= d + pd.Timedelta(days=14)))
    cover = (P.index >= S[sig].dropna().index.min()) & (P.index <= S[sig].dropna().index.max()); mask &= cover
    for strait in ["taiwan_strait", "luzon_strait", "mindoro_strait", "malacca_strait"]:
        r = study(resid(strait), ds, pd.Series(mask, index=P.index)); R[(sig, strait)] = r
        L.append(f"| {sig} ({len(ds)} spikes) | {strait} | {r['k']} | {f(r['car'])} | {r['p']:.2f} | {f(r['pre'])} |")
L.append("\n## (3) Weekly regressions (HAC): mean abnormal transits(t+1) ~ signal z(t)\n")
for strait in ["taiwan_strait", "mindoro_strait"]:
    r = resid(strait)
    for sig in ["mfa_threat_share", "mfa_threat_novel_share", "mfa_action_share", "mnd_aircraft"]:
        W = pd.DataFrame({"r": r, "x": S[sig].reindex(P.index)}).resample("W").mean().dropna()
        xz = (W.x - W.x.rolling(26, min_periods=8).mean()) / W.x.rolling(26, min_periods=8).std()
        d = pd.concat([W.r.shift(-1), xz], axis=1, keys=["y", "x"]).dropna()
        m = sm.OLS(d.y, sm.add_constant(d.x)).fit(cov_type="HAC", cov_kwds={"maxlags": 4})
        L.append(f"- {strait} ~ {sig}: beta={m.params.x:+.4f} (≈{100*m.params.x:+.2f}% per SD), p={m.pvalues.x:.2f}, R2={m.rsquared:.3f}, weeks={len(d)}")
(ROOT / "reports/results_M3_text_signals.md").write_text("\n".join(L) + "\n"); print("\n".join(L))
# ---- figure 2
fig, ax = plt.subplots(3, 1, figsize=(13, 10), sharex=True)
for col, c, lab in [("mfa_threat_share", "tab:red", "MFA threat share (all)"), ("mfa_threat_novel_share", "darkred", "MFA threat share (excl. boilerplate)")]:
    ax[0].plot(S[col].dropna().rolling(10, min_periods=3).mean(), color=c, lw=1, label=lab)
ax[0].plot(S["mfa_action_share"].dropna().rolling(10, min_periods=3).mean(), color="tab:blue", lw=1, label="MFA action share")
ax[0].set_ylabel("share of topic sentences\n(10-presser avg)"); ax[0].legend(fontsize=8, loc="upper left")
ax[0].set_title("Classifier-derived signals from MFA press conferences (EN+ZH, 2022-07→2026-10)", fontsize=10)
mn = S["mnd_aircraft"].dropna(); ax[1].plot(mn.asfreq("D").rolling(7, min_periods=3).mean(), color="k", lw=1, label="MND: PLA aircraft (7-report avg)")
ax[1].plot(S["mnd_ships"].dropna().asfreq("D").rolling(7, min_periods=3).mean(), color="tab:green", lw=1, label="MND: PLAN ships")
ax[1].axvline(pd.Timestamp("2022-11-13"), color="grey", ls=":")
ax[1].legend(fontsize=8, loc="upper left"); ax[1].set_title("Taiwan MND PLA activity reports (before 2022-11: SW-ADIZ incursions only; gaps = counts only in PDF/image or missing)", fontsize=10)
for _, r in EV.iterrows():
    for a in ax[:2]: a.axvline(r.public_date, color="tab:red" if r.theater == "taiwan" else "tab:blue", ls="-" if r.category == "action" else "--", alpha=.25, lw=.7)
rt = resid("taiwan_strait"); ax[2].plot(rt * 100, color="grey", lw=.7, label="Taiwan Strait abnormal transits (weather-adj., %)")
for d in spikes(S["mfa_threat_share"]): ax[2].axvline(d, color="tab:red", lw=1, alpha=.6)
ax[2].axhline(0, color="k", lw=.5); ax[2].set_ylabel("%"); ax[2].legend(fontsize=8, loc="upper left")
ax[2].set_title("Cost: abnormal transits; red lines = MFA threat-share spike days (z>3)", fontsize=10)
fig.suptitle("PRELIMINARY — Text signals vs. costs (classifier labels from two AI annotators; no human validation yet)", fontweight="bold")
fig.tight_layout(); fig.savefig(ROOT / "reports/figures/fig02_text_signals.png", dpi=120); print("saved")
